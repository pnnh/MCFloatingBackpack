package pnnh.mcfloatingbackpack.snapshot;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

/**
 * 057: what the snapshot folder of a world remembers between runs (its {@code state.properties}): the mod version of the last run, the
 * number of the last change of version, the version before it, how many backpacks that change pinned a snapshot of, and which players
 * were already told about it. The text is {@code key=value} lines; anything that cannot be read means "no record" (the whole file) or is
 * left out (one bad player in the list); nothing here throws. Pure logic.
 */
public record SnapshotState(String lastModVersion, long changeId, String fromVersion, int pinned, List<UUID> notified) {
    /** At most this many players are remembered; beyond it the oldest are dropped. */
    public static final int MAX_NOTIFIED = 10_000;

    public SnapshotState {
        lastModVersion = lastModVersion == null ? "" : lastModVersion.strip();
        fromVersion = fromVersion == null ? "" : fromVersion.strip();
        List<UUID> list = new ArrayList<>(notified == null ? List.of() : notified);
        if (list.size() > MAX_NOTIFIED) {
            list = new ArrayList<>(list.subList(list.size() - MAX_NOTIFIED, list.size()));
        }
        notified = List.copyOf(list);
    }

    /** The same state with this player added to those that were told (nothing changes if they already were). */
    public SnapshotState withNotified(UUID player) {
        if (notified.contains(player)) {
            return this;
        }
        List<UUID> list = new ArrayList<>(notified);
        list.add(player);
        return new SnapshotState(lastModVersion, changeId, fromVersion, pinned, list);
    }

    /** Whether more players are remembered than {@link #MAX_NOTIFIED} (that is, whether adding one drops the oldest). */
    public boolean full() {
        return notified.size() >= MAX_NOTIFIED;
    }

    public String toText() {
        StringBuilder out = new StringBuilder();
        out.append("# generated by MCFloatingBackpack; safe to delete (it is written again; the notices may repeat once)\n");
        out.append("last_mod_version=").append(lastModVersion).append('\n');
        out.append("change_id=").append(changeId).append('\n');
        out.append("from_version=").append(fromVersion).append('\n');
        out.append("pinned=").append(pinned).append('\n');
        out.append("notified=");
        for (int i = 0; i < notified.size(); i++) {
            out.append(i == 0 ? "" : ",").append(notified.get(i));
        }
        out.append('\n');
        return out.toString();
    }

    /** @return the state the text says, or empty when it has no record: no version, or a change number that is not a whole number */
    public static Optional<SnapshotState> parse(String text) {
        if (text == null) {
            return Optional.empty();
        }
        String version = null;
        Long id = null;
        String from = "";
        int pinned = 0;
        List<UUID> notified = new ArrayList<>();
        for (String line : text.split("\\R")) {
            String trimmed = line.strip();
            int eq = trimmed.indexOf('=');
            if (trimmed.isEmpty() || trimmed.startsWith("#") || eq <= 0) {
                continue;
            }
            String key = trimmed.substring(0, eq).strip();
            String value = trimmed.substring(eq + 1).strip();
            switch (key) {
                case "last_mod_version" -> version = value;
                case "change_id" -> id = parseLong(value);
                case "from_version" -> from = value;
                case "pinned" -> {
                    Long n = parseLong(value);
                    pinned = n == null || n < 0 || n > Integer.MAX_VALUE ? 0 : n.intValue();
                }
                case "notified" -> {
                    for (String part : value.split(",")) {
                        UUID uuid = parseUuid(part.strip());
                        if (uuid != null && !notified.contains(uuid)) {
                            notified.add(uuid);
                        }
                    }
                }
                default -> {
                }
            }
        }
        if (version == null || version.isEmpty() || id == null || id < 0) {
            return Optional.empty();
        }
        return Optional.of(new SnapshotState(version, id, from, pinned, notified));
    }

    private static Long parseLong(String value) {
        try {
            return Long.valueOf(value);
        } catch (NumberFormatException notANumber) {
            return null;
        }
    }

    private static UUID parseUuid(String value) {
        if (value.isEmpty()) {
            return null;
        }
        try {
            return UUID.fromString(value);
        } catch (IllegalArgumentException notAUuid) {
            return null;
        }
    }
}
